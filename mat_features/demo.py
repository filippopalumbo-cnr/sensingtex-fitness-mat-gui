"""Deterministic synthetic sensor maps; never presented as participant data."""
import json
from pathlib import Path
import numpy as np


def generate_demo(output):
    output = Path(output)
    if output.exists() and (not output.is_dir() or any(output.iterdir())):
        raise ValueError("Demo output must be a new or empty directory")
    output.mkdir(parents=True, exist_ok=True)
    elapsed = np.arange(0, 24, .1)
    rr, cc = np.meshgrid(np.arange(80), np.arange(28), indexing="ij")
    maps = []
    for time in elapsed:
        shift = 1.5 * np.sin(2*np.pi*time/5)
        left = np.exp(-((rr-38-shift)**2/35 + (cc-8)**2/5))
        right = np.exp(-((rr-40-shift)**2/35 + (cc-20)**2/5))
        balance = .12 * np.cos(2*np.pi*time/5)
        pressure = 2000 * (1+.06*np.sin(2*np.pi*time/3)) * ((1+balance)*left + (1-balance)*right)
        maps.append(np.rint(pressure).astype(int).ravel() if 2 <= time < 22 else np.zeros(2240, dtype=int))
    data = np.column_stack((1736942400.0 + elapsed, maps))
    np.savetxt(output / "SYNTHETIC_demo.csv", data, delimiter=",", fmt=["%.6f"]+["%d"]*2240,
               header="Timestamp,"+",".join(f"Sensor_{i}" for i in range(2240)), comments="")
    (output / "README.txt").write_text("SYNTHETIC DEMONSTRATION ONLY.\nGenerated by mat-features demo; not a human recording.\n", encoding="utf-8")
    (output / "generation.json").write_text(json.dumps({"synthetic": True, "seed": "deterministic",
        "frames": len(data), "rows": 80, "cols": 28, "nominal_hz": 10}, indent=2)+"\n", encoding="utf-8")
    return output / "SYNTHETIC_demo.csv"
